# ─── I2/I3 composition helpers ────────────────────────────────────────────────
#
# _compose(sections): merge list[list[str]] → list[str], skipping empty sections.
#   Lets each adapter top-level renderer declare its block order in one place,
#   so adding a new section is a single list-append (no nested if/else churn).
#
# _est_tokens / _truncate_to_budget: per-section budget enforcement.
#   Every new renderer (_render_stack/_runtime/_placement_section) accepts a
#   max_tokens cap and the helper trims overflowing tail lines, appending a
#   "(truncated to N tokens)" marker so the agent knows the cut was intentional.

def _compose(sections: list[list[str]]) -> list[str]:
    """Concatenate non-empty sections in order. Each section is already
    formatted (its own header + trailing blank line). Empty/None sections
    are skipped silently."""
    out: list[str] = []
    for section in sections:
        if section:
            out.extend(section)
    return out


def _est_tokens(text: str) -> int:
    """Rough token estimate (1 token ≈ 4 chars). Matches the heuristic
    used by the existing _WARM_TOKEN_BUDGET enforcement."""
    return max(1, len(text) // 4)


def _truncate_to_budget(lines: list[str], max_tokens: int) -> list[str]:
    """Keep header + body lines until adding the next would exceed budget.
    Always keeps at least 1 line. Appends an explicit truncation marker
    when content was dropped, so agents know the cut was intentional."""
    if max_tokens <= 0 or not lines:
        return lines
    out: list[str] = []
    used = 0
    for ln in lines:
        cost = _est_tokens(ln)
        if used + cost > max_tokens and out:
            out.append(f"_(truncated to ~{max_tokens} tokens)_")
            out.append("")
            return out
        out.append(ln)
        used += cost
    return out


# ─── Evidence preservation ────────────────────────────────────────────────────
#
# Single point of formatting for assertion bullets. Whenever an Assertion
# carries `evidence` (file:line populated during canonicalization), we
# surface it inline so the agent can verify the claim against source
# without re-reading the repo. Empty evidence renders nothing.

def _fmt_assertion_bullet(a: Assertion, stale_suffix: str = "") -> str:
    """Render an assertion as a markdown bullet, preserving evidence inline.
    Format: `- {claim}{stale}  *(src/foo.ts:42)*`"""
    ev = a.evidence
    suffix = stale_suffix
    if ev:
        # Trailing space before italics ensures clean rendering across
        # markdown viewers when stale_suffix is empty.
        suffix = f"{stale_suffix}  *({ev})*"
    return f"- {a.claim}{suffix}"


# ─── Stack section (C2 normalized + I3 budgeted) ──────────────────────────────
#
# Renders normalized StackContext as a compact Tech Stack block.
# Anti-hallucination: if StackContext.is_empty() the section is omitted —
# never falls back to hardcoded defaults. Each subfield is rendered only
# if populated, so missing data shows as absence (not "Unknown").

_STACK_DEFAULT_BUDGET = 200


def _render_stack_section(
    stack: StackContext | None,
    max_tokens: int = _STACK_DEFAULT_BUDGET,
) -> list[str]:
    if stack is None or stack.is_empty():
        return []
    lines: list[str] = ["## Tech Stack", ""]
    field_order = (
        ("Languages", stack.languages),
        ("Frameworks", stack.frameworks),
        ("Runtimes", stack.runtimes),
        ("Package managers", stack.package_managers),
    )
    for label, values in field_order:
        if values:
            lines.append(f"- **{label}**: {', '.join(values)}")
    lines.append("")
    return _truncate_to_budget(lines, max_tokens)


# ─── Placement section (I5/I6 + I3 budgeted) ──────────────────────────────────
#
# Renders synthesis/placement-map.json as a "Code Placement" block. Each entry
# is rendered as "{category} → `{path}` ({coverage_pct})" with a low-confidence
# warning so agents know to grep before assuming the convention applies.
# Section is omitted entirely when the map is empty/missing.

_PLACEMENT_DEFAULT_BUDGET = 300


def _render_placement_section(
    placement: dict | None,
    max_tokens: int = _PLACEMENT_DEFAULT_BUDGET,
) -> list[str]:
    if not placement or placement.get("status") != "generated":
        return []
    entries = placement.get("placements") or []
    if not entries:
        return []
    lines: list[str] = ["## Code Placement", ""]
    for p in entries:
        cat = p.get("category", "Unknown")
        path = p.get("path", "")
        conf = p.get("confidence", "low")
        pct = p.get("coverage_pct", 0)
        pct_str = f"{int(round(pct * 100))}%"
        if conf == "low":
            lines.append(
                f"- **{cat}** → `{path}` ({pct_str}) ⚠️ convenção dispersa — grep antes de assumir"
            )
        else:
            lines.append(f"- **{cat}** → `{path}` ({pct_str})")
    lines.append("")
    return _truncate_to_budget(lines, max_tokens)


def _load_placement_map(maes_dir: Path) -> dict | None:
    """Load synthesis/placement-map.json. Returns None when absent/unreadable."""
    p = maes_dir / "synthesis" / "placement-map.json"
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None


# ─── Runtime section (I4 + I3 budgeted) ───────────────────────────────────────
#
# Renders RuntimeContext as a "Runtime Commands" block. When the source file
# (context/human/runtime.md) is missing or its last_verified is older than 30
# days, prefixes the block with ⚠️ so agents know the commands may not work
# anymore. Section is omitted entirely when no commands are defined.

_RUNTIME_DEFAULT_BUDGET = 200
_RUNTIME_FIELD_LABELS = (
    ("test", "Test"),
    ("build", "Build"),
    ("lint", "Lint"),
    ("run", "Run"),
    ("migrate", "Migrate"),
    ("test_pattern", "Test pattern"),
    ("run_module_test", "Module test"),
)


def _render_runtime_section(
    runtime: RuntimeContext | None,
    max_tokens: int = _RUNTIME_DEFAULT_BUDGET,
) -> list[str]:
    if runtime is None or runtime.is_empty():
        return []
    lines: list[str] = ["## Runtime Commands", ""]
    if runtime.staleness_warning:
        lv = runtime.last_verified or "never"
        lines.append(
            f"⚠️ Runtime context may be stale (last_verified: {lv}). "
            "Re-run and update `.maes/context/human/runtime.md` before trusting."
        )
        lines.append("")
    for key, label in _RUNTIME_FIELD_LABELS:
        val = getattr(runtime, key, "")
        if val:
            lines.append(f"- **{label}**: `{val}`")
    lines.append("")
    return _truncate_to_budget(lines, max_tokens)


def _load_agents(maes_dir: Path) -> list[dict]:
    agents_dir = maes_dir / "agents"
    if not agents_dir.exists():
        return []
    agents = []
    try:
        import yaml
    except ImportError:
        return []
    for f in sorted(agents_dir.glob("*.agent.yaml")):
        try:
            data = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
            data.setdefault("_file", f.name)
            agents.append(data)
        except Exception:
            continue
    return agents


# ─── Context assembly for an agent ────────────────────────────────────────────

def _keyword_set(text: str) -> frozenset[str]:
    import re
    stop = frozenset({"a", "o", "e", "de", "da", "do", "em", "um", "uma",
                      "the", "is", "to", "of", "and", "or", "in", "for",
                      "que", "se", "na", "no", "os", "as", "com", "por"})
    tokens = re.sub(r"[^\w\s]", " ", text.lower()).split()
    return frozenset(t for t in tokens if t not in stop and len(t) > 2)


def _path_score(a_paths: list[str], scope_paths: list[str]) -> float:
    for ap in a_paths:
        ap_root = ap.split("/")[0] if "/" in ap else ap
        for sp in scope_paths:
            sp_root = sp.split("/")[0] if "/" in sp else sp
            if ap_root and (ap_root in sp_root or sp_root in ap_root):
                return 0.8
    return 0.0


def _score_assertion(
    a: Assertion,
    scope_domains: list[str],
    scope_paths: list[str],
    task_keywords: frozenset,
    today: date,
) -> float:
    # Domain overlap: check if scope domains appear in claim or subject
    claim_lower = a.claim.lower()
    subject_lower = (a.subject or "").lower()
    if scope_domains:
        matched = sum(
            1 for d in scope_domains
            if d.lower() in claim_lower or d.lower() in subject_lower
        )
        domain_score = matched / max(len(scope_domains), 1)
    else:
        domain_score = 0.5
    path_score = _path_score(a.paths, scope_paths)
    task_score = 0.0
    if task_keywords:
        claim_kw = _keyword_set(a.claim)
        overlap = len(claim_kw & task_keywords)
        task_score = min(1.0, overlap / max(len(task_keywords), 1))
    layer_weight = (8 - a.layer) / 7
    conf_weight = {"explicit": 1.0, "inferred-high": 0.9,
                   "inferred-medium": 0.7, "assumed": 0.3}.get(a.confidence, 0.5)
    stale = staleness_score(a, today)
    staleness_penalty = 0.6 if stale > 0.6 else 1.0
    base = domain_score * 0.30 + path_score * 0.25 + layer_weight * 0.15 + task_score * 0.30
    return base * conf_weight * staleness_penalty


def _claim_overlaps(claim: str, domains: list[str], paths: list[str]) -> bool:
    """True if claim text is related to agent domains or top-level path prefixes."""
    lower = claim.lower()
    if any(d.lower() in lower for d in domains if d):
        return True
    return any(p.split("/")[0].lower() in lower for p in paths if "/" in p)


def _filter_hot_for_agent(
    rules: list[dict],
    scope_domains: list[str],
    scope_paths: list[str],
) -> list[dict]:
    """Layer 1 (compliance) always included. Layers 2–3 filtered by domain/path relevance."""
    if not scope_domains and not scope_paths:
        return list(rules)
    return [
        rule for rule in rules
        if rule.get("layer") == 1
        or _claim_overlaps(rule.get("claim", ""), scope_domains, scope_paths)
    ]


def _assertions_for_agent(
    agent: dict,
    assertions: list[Assertion],
    anti_hallucination: list[dict],
    warm_token_budget: int = 4000,
    task: str = "",
) -> tuple[list[dict], list[Assertion]]:
    """Return (hot_rules, warm_assertions) for this agent."""
    scope_paths: list[str] = agent.get("scope", {}).get("paths", [])
    scope_domains: list[str] = agent.get("domains", [])
    task_keywords = _keyword_set(task) if task else frozenset()
    today = date.today()

    hot = _filter_hot_for_agent(anti_hallucination, scope_domains, scope_paths)

    hot_types = frozenset({"CONSTRAINT", "COMPLIANCE"})
    hot_confidences = frozenset({"explicit", "inferred-high"})
    scored: list[tuple[float, Assertion]] = []

    for a in assertions:
        if a.type in hot_types and a.confidence in hot_confidences:
            continue  # already in hot
        score = _score_assertion(a, scope_domains, scope_paths, task_keywords, today)
        scored.append((score, a))

    scored.sort(key=lambda x: x[0], reverse=True)
    warm: list[Assertion] = []
    tokens_used = 0
    for score, a in scored:
        if score < 0.1:
            break
        est_tokens = max(1, len(a.claim) // 4)
        if tokens_used + est_tokens > warm_token_budget:
            break
        warm.append(a)
        tokens_used += est_tokens

    return hot, warm


