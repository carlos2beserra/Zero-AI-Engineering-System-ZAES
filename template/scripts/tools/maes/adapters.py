def _render_windsurf_rules(
    project_name: str,
    assertions: list[Assertion],
    anti_hallucination: list[dict],
    guards: list[dict],
    stack: StackContext | None = None,
    placement: dict | None = None,
    runtime: RuntimeContext | None = None,
) -> str:
    header = [
        f"# {project_name} — MAES Context",
        "",
        _GENERATED_HEADER,
        _GENERATED_SOURCE,
        "",
    ]

    critical_rules: list[str] = []
    if anti_hallucination:
        critical_rules = ["## Critical Rules (always apply)", ""]
        for rule in anti_hallucination:
            layer_name = LAYER_NAMES.get(rule.get("layer", 7), "")
            critical_rules.append(f"- **[{layer_name}]** {rule['claim']}")
        critical_rules.append("")

    enforcement_blocked = [
        g for g in guards
        if g.get("guard_type") == "enforcement" and g.get("policy") == "block"
    ]
    blocked_section: list[str] = []
    if enforcement_blocked:
        blocked_section = ["## Blocked Actions", ""]
