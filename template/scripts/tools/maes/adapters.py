def _render_hot_context_section(anti_hallucination: list[dict]) -> list[str]:
    if not anti_hallucination:
        return []
    lines = [
        "## Regras Críticas (Hot Context)",
        "",
        "As regras abaixo têm prioridade máxima. Nunca ignorar.",
        "",
    ]
    for rule in anti_hallucination:
        layer_name = LAYER_NAMES.get(rule.get("layer", 7), "")
        lines.append(f"- **[{layer_name}]** {rule['claim']}")
    lines.append("")
    return lines


def _render_guards_section(guards: list[dict]) -> list[str]:
    critical = [g for g in guards if g.get("policy") == "block"]
    if not critical:
        return []
    lines = ["## Guards Ativos", ""]
    for g in critical[:10]:
        paths = g.get("paths", [])
        lines.append(f"- `{', '.join(paths[:2])}` — {g.get('claim', '')}")
    lines.append("")
    return lines


def _render_agents_section(agents: list[dict]) -> list[str]:
    active = [ag for ag in agents if ag.get("enabled", True)]
    if not active:
        return []
    lines = [
        "## Agents Disponíveis",
        "",
        "| Agent | Scope | Comando |",
        "|-------|-------|---------|",
    ]
    for ag in active:
        name = ag.get("name", ag.get("id", "unknown"))
        ag_id = ag.get("id", "")
        paths = ag.get("scope", {}).get("paths", [])
        scope_str = ", ".join(paths[:2]) if paths else "global"
        lines.append(f"| {name} | `{scope_str}` | `/{ag_id}` |")
    lines += ["", "", "## Roteamento por Task", ""]
    for ag in active:
        ag_id = ag.get("id", "")
        paths = ag.get("scope", {}).get("paths", [])
        if paths:
            lines.append(f"- Tasks em `{paths[0]}`: use `/{ag_id}`")
    lines.append("")
    return lines


_WARM_TOKEN_BUDGET = 4000


def _render_warm_context_section(
    assertions: list[Assertion],
    hot_claims: set[str] | None = None,
) -> list[str]:
    today = date.today()
    warm = [a for a in assertions
            if 4 <= a.layer <= 6
            and (hot_claims is None or a.claim not in hot_claims)]
    if not warm:
        return []
    lines = ["## Contexto do Projeto", ""]
    by_layer: dict[int, list[Assertion]] = {}
    for a in warm:
        by_layer.setdefault(a.layer, []).append(a)
    tokens_used = 0
    for layer in sorted(by_layer):
        layer_name = LAYER_NAMES.get(layer, f"layer-{layer}")
        lines.append(f"### {layer_name.title()}")
        lines.append("")
        for a in by_layer[layer]:
            est = max(1, len(a.claim) // 4)
            if tokens_used + est > _WARM_TOKEN_BUDGET:
                break
            stale = " ⚠️" if staleness_score(a, today) > 0.6 else ""
            lines.append(_fmt_assertion_bullet(a, stale))
            tokens_used += est
        lines.append("")
    return lines


def _render_claude_md(
    project_name: str,
    agents: list[dict],
    anti_hallucination: list[dict],
    guards: list[dict],
    assertions: list[Assertion] | None = None,
    stack: StackContext | None = None,
    placement: dict | None = None,
    runtime: RuntimeContext | None = None,
) -> str:
    header = [
        f"# {project_name} — MAES Context",
        "",
        "> Gerado automaticamente por `maes sync`. Não editar manualmente.",
        "> Fonte: `.maes/synthesis/`. Para alterar, edite `.maes/context/human/`.",
        "",
    ]
    warm_section: list[str] = []
    if assertions:
        hot_claims = {r["claim"] for r in anti_hallucination}
        warm_section = _render_warm_context_section(assertions, hot_claims=hot_claims)

    # I2: declarative section composition — adding a new V1 block is a one-line
    # insert here; ordering is the only coupling between items.
    body = _compose([
        _render_agents_section(agents),
        _render_hot_context_section(anti_hallucination),
        _render_stack_section(stack),
        _render_runtime_section(runtime),
        _render_placement_section(placement),
        _render_guards_section(guards),
        warm_section,
    ])
    footer = [
        "## Prioridade de Contexto",
        "",
        "1. **Compliance + Security** (camadas 1-2) — invioláveis",
        "2. **Contracts + Architecture** (camadas 3-4) — ceder somente para 1-2",
        "3. **Domain rules** (camada 5) — regras de negócio do projeto",
        "4. **Engineering principles** (camada 6) — padrões do time",
        "5. **Inferred patterns** (camada 7) — padrões detectados no código",
        "",
        "Em caso de conflito: camada menor vence; mesma camada → consultar humano.",
        "",
        "## Setup",
        "",
        "Skins e prompts: `.maes/adapters/claude/commands/`",
        "Para re-gerar este arquivo: `maes sync`",
    ]
    return "\n".join(header + body + footer) + "\n"


def _render_warm_layers_section(warm: list[Assertion]) -> list[str]:
    if not warm:
        return []
    today = date.today()
    lines: list[str] = [_PROJECT_CONTEXT_HEADING, ""]
    by_layer: dict[int, list[Assertion]] = {}
    for a in warm:
        by_layer.setdefault(a.layer, []).append(a)
    for layer in sorted(by_layer):
        layer_name = LAYER_NAMES.get(layer, f"layer-{layer}")
        lines.append(f"### {layer_name.title()}")
        lines.append("")
        for a in by_layer[layer]:
            stale = " ⚠️ *contexto pode estar desatualizado*" if staleness_score(a, today) > 0.6 else ""
            lines.append(_fmt_assertion_bullet(a, stale))
        lines.append("")
    return lines


def _render_mutation_guards_section(mutation_paths: list, blocked_paths: list) -> list[str]:
    if not mutation_paths and not blocked_paths:
        return []
    lines: list[str] = ["## Guards de Mutação", ""]
    if blocked_paths:
        lines.append(
            f"**BLOQUEADO** (não modificar sem aprovação explícita): "
            f"{', '.join(f'`{p}`' for p in blocked_paths)}"
        )
    if mutation_paths:
        lines.append(
            f"**Requer aprovação antes de modificar**: "
            f"{', '.join(f'`{p}`' for p in mutation_paths)}"
        )
    lines.append("")
    return lines


def _render_delegates_section(delegates: dict) -> list[str]:
    if not delegates:
        return []
    lines: list[str] = ["## Delegação", ""]
    for target_id, reason in delegates.items():
        lines.append(f"- Delegar para `/{target_id}` {reason}")
    lines.append("")
    return lines


def _mistake_in_scope(a_paths: list[str], scope_paths: list[str]) -> bool:
    """True if a mistake's file paths overlap with the agent's scope paths."""
    if not a_paths:
        return True
    if not scope_paths or "**" in scope_paths:
        return True
    for mp in a_paths:
        mp_norm = mp.replace("\\", "/").split(":")[0]
        for sp in scope_paths:
            sp_base = sp.replace("**", "").replace("*", "").strip("/")
            if sp_base and (mp_norm.startswith(sp_base) or sp_base in mp_norm):
                return True
    return False


def _render_common_mistakes_section(
    warm: list[Assertion],
    scope_paths: list[str] | None = None,
) -> list[str]:
    _scope = scope_paths or []
    # Assertions with code_examples are from ai_likely_mistakes section
    mistakes = [
        a for a in warm
        if a.code_examples
        and _mistake_in_scope(a.paths, _scope)
    ]
    if not mistakes:
        return []
    lines: list[str] = ["## Erros Comuns", ""]
    for a in mistakes:
        ex = a.code_examples[0]
        if ex.get("trigger") or "[trigger]" in a.claim:
            lines.append(f"**Trigger:** {ex.get('trigger', a.claim)}")
        if ex.get("wrong") and ex.get("correct"):
            lines.append(f"```python\n# ❌ ERRADO\n{ex['wrong']}\n\n# ✅ CORRETO\n{ex['correct']}\n```")
        lines.append("")
    return lines


def _render_claude_command(agent: dict, hot_rules: list[dict],
                            warm: list[Assertion]) -> str:
    name = agent.get("name", agent.get("id", "agent"))
    description = agent.get("description", "")
    persona = agent.get("persona", "").strip()
    scope_paths = agent.get("scope", {}).get("paths", [])
    delegates = agent.get("delegates_to", {})
    guards_agent = agent.get("guards", {})
    workflow = agent.get("workflow", {})
    argument_hint = workflow.get("argument_hint", "")

    desc_line = f"{name} — {description}"
    if argument_hint:
        desc_line += f" — args: {argument_hint}"

    lines = [
        "---",
        f"description: {desc_line}",
        "---",
        "",
        f"# {name}",
        "",
    ]

    if persona:
        lines += [persona, ""]

    lines += [
        "## Escopo",
        "",
        f"Paths: {', '.join(f'`{p}`' for p in scope_paths) or 'global'}",
        "",
    ]

    if hot_rules:
        lines += ["## Regras Críticas (sempre aplicar)", ""]
        for rule in hot_rules:
            lines.append(f"- {rule['claim']}")
        lines.append("")

    lines += _render_common_mistakes_section(warm, scope_paths=scope_paths)
    lines += _render_warm_layers_section(warm)

    mutation_paths = guards_agent.get("mutation_requires_approval", [])
    blocked_paths = guards_agent.get("blocked_mutations", [])
    lines += _render_mutation_guards_section(mutation_paths, blocked_paths)
    lines += _render_delegates_section(delegates)

    workflow_content = workflow.get("content", "").strip()
    if workflow_content:
        lines += ["## Workflow", "", workflow_content, ""]

    return "\n".join(lines) + "\n"


def generate_claude_adapter(
    maes_dir: Path,
    state: State,
    project_name: str,
) -> dict[str, str]:
    """Return {relative_path: content} for Claude Code adapter files."""
    agents = _load_agents(maes_dir)
    anti_hallucination = derive_hot_context(state.assertions)
    guards = derive_guards(state.assertions)
    files: dict[str, str] = {}

    files["CLAUDE.md"] = _render_claude_md(
        project_name, agents, anti_hallucination, guards,
        assertions=state.assertions,
        stack=state.stack,
        placement=_load_placement_map(maes_dir),
        runtime=state.runtime,
    )

    for ag in agents:
        ag_id = ag.get("id", "")
        if not ag_id:
            continue
        hot, warm = _assertions_for_agent(
            ag, state.assertions, anti_hallucination
        )
        files[f".claude/commands/{ag_id}.md"] = _render_claude_command(ag, hot, warm)

    return files


# ─── Cursor adapter ────────────────────────────────────────────────────────────

def _render_cursor_rule(agent: dict, hot_rules: list[dict],
                         warm: list[Assertion]) -> str:
    name = agent.get("name", agent.get("id", "agent"))
    description = agent.get("description", "")
    scope_paths = agent.get("scope", {}).get("paths", [])
    persona = agent.get("persona", "").strip()
    globs_str = json_safe_list(scope_paths[:4])

    lines = [
        "---",
        f"description: {name} — {description}",
        f"globs: {globs_str}",
        "alwaysApply: false",
        "---",
        "",
        f"# {name}",
        "",
    ]

    if persona:
        lines += [persona, ""]

    if hot_rules:
        lines += ["## Regras Críticas", ""]
        for rule in hot_rules:
            lines.append(f"- {rule['claim']}")
        lines.append("")

    if warm:
        hot_claim_set = {r["claim"] for r in hot_rules} if hot_rules else set()
        warm_filtered = [a for a in warm if a.claim not in hot_claim_set]
        if warm_filtered:
            lines += ["## Contexto", ""]
            for a in warm_filtered:
                lines.append(_fmt_assertion_bullet(a))
            lines.append("")

    return "\n".join(lines) + "\n"


def json_safe_list(items: list[str]) -> str:
    if not items:
        return "[]"
    inner = ", ".join(f'"{i}"' for i in items)
