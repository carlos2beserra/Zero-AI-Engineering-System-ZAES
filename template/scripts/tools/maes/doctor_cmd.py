"""maes doctor — supplementary diagnostic checks."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Callable

# Schema the installed CLI produces. Kept here so `doctor` can tell "regenerate the
# map" apart from "the code that ran is not the installed one".
_ARCH_MAP_SCHEMA = "2.1"


def _collect_agent_path_violations(
    agent_files: list,
    yaml,
) -> list[tuple[str, str]]:
    """Return (filename, path) pairs for scope.paths entries that violate the single-path invariant."""
    from .quickstart_cmd import _is_single_path_unit

    violations: list[tuple[str, str]] = []
    for agent_file in agent_files:
        try:
            data = yaml.safe_load(agent_file.read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001  yaml.YAMLError or OSError
            continue
        if not isinstance(data, dict):
            continue
        paths = (data.get("scope") or {}).get("paths") or []
        for p in paths:
            if isinstance(p, str) and not _is_single_path_unit(p):
                violations.append((agent_file.name, p))
    return violations


def _check_agent_scope_paths(
    agents_dir: Path,
    ok: Callable[[str], None],
    warn: Callable[[str], None],
) -> None:
    """Verify that every scope.paths entry in agent YAMLs is a single-path unit.

    Uses _is_single_path_unit() from quickstart_cmd as the single source of truth —
    a path is valid if no segment contains whitespace. Multi-path descriptions
    generated by the LLM (e.g. 'app/a/ and app/b/') always embed whitespace.
    """
    try:
        import yaml  # type: ignore[import-untyped]
    except ImportError:
        return

    if not agents_dir.exists():
        return

    agent_files = sorted(agents_dir.glob("*.agent.yaml"))
    if not agent_files:
        return

    violations = _collect_agent_path_violations(agent_files, yaml)
    if not violations:
        ok(f"{len(agent_files)} agent YAML(s) — all scope.paths valid")
        return

    by_agent: dict[str, list[str]] = {}
    for agent_name, path in violations:
        by_agent.setdefault(agent_name, []).append(path)

    for agent_name in sorted(by_agent):
        for path in by_agent[agent_name]:
            warn(
                f"agent/{agent_name}: scope.paths '{path}' "
                "violates single-path-unit invariant — re-run `maes sync` to regenerate"
            )


def _check_architecture_map(
    maes_dir: Path,
    info: Callable[[str], None],
) -> None:
    """Report the status of architecture_map.json as an informational fact.

    Per I2: absence is valid — this check never emits warnings or errors.
    It describes the observable state so the operator has visibility.
    """
    arch_map_path = maes_dir / "context" / "inferred" / "architecture_map.json"
    if not arch_map_path.exists():
        info("architecture_map.json: file not found (run `maes build-arch-map` to generate)")
        return

    try:
        data = json.loads(arch_map_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        info("architecture_map.json: present but unreadable")
        return

    status = data.get("status", "unknown")
    if status == "generated":
        node_count = len(data.get("nodes", []))
        info(f"architecture_map.json: {node_count} node(s) generated")
    elif status == "empty_no_nodes":
        info("architecture_map.json: 0 nodes found during last analysis")
    elif status == "no_arch_map":
        info("architecture_map.json: arch analysis did not run during last analyze")
    else:
        info(f"architecture_map.json: status={status!r}")

    _report_arch_map_schema(data, info)


def _report_arch_map_schema(
    data: dict,
    info: Callable[[str], None],
) -> None:
    """Safety net the user finds on their own: a stale schema explains the omitted
    Code Placement, and a schema that never advances after `maes build-arch-map` means
    the Analyze that ran is not the installed one (ADR 0009).
    """
    found = str(data.get("schema_version") or "")
    if found == _ARCH_MAP_SCHEMA:
        ratio = (data.get("diagnostic_metrics") or {}).get("sampling_ratio")
        if isinstance(ratio, (int, float)):
            info(
                f"architecture_map.json: schema {found}, "
                f"sampling_ratio={ratio:.2f} (share of source files read)"
            )
        return
    info(
        f"architecture_map.json: schema {found or 'ausente'} "
        f"(esperado {_ARCH_MAP_SCHEMA}) — rode `maes build-arch-map`; se persistir, o "
        "Analyze executado não corresponde à versão instalada"
    )
