# ─── Project roots (multirepo / monorepo support) ─────────────────────────────
#
# _PRIORITY_FILES used to be resolved only at project_dir, so in a multirepo
# workspace NO package.json was ever found and _detect_frontend_framework
# returned None — is_frontend_project became false by absence of evidence rather
# than by observation.
#
# Order is PRIORITY, not just a name list: cutting purely alphabetically could
# fill every slot with auxiliary packages/ while the application's package.json
# is never collected — the same bug through another door.
_SUBPROJECT_MARKERS = (
    "package.json", "pyproject.toml", "go.mod", "Cargo.toml",
    "pom.xml", "build.gradle", "composer.json", "Gemfile",
)

# Protection limit, NOT an architectural limit of the platform: inventory,
# topology and nodes still cover the whole workspace — only MANIFEST collection
# is capped, because dozens of packages x ~60 _PRIORITY_FILES entries would
# exhaust the priority phase budget on manifests alone. Initial value, revisable.
_MAX_PROJECT_ROOTS = 8
_MAX_PROJECT_ROOT_DEPTH = 2


def _marker_rank(d: Path) -> int:
    """Priority index of the strongest manifest in `d`; len(markers) if none."""
    for i, marker in enumerate(_SUBPROJECT_MARKERS):
        if (d / marker).is_file():
            return i
    return len(_SUBPROJECT_MARKERS)


def _has_manifest(d: Path) -> bool:
    return _marker_rank(d) < len(_SUBPROJECT_MARKERS)


def _candidate_root_dirs(project_dir: Path, depth: int) -> "list[Path]":
    """Directories at exactly `depth` levels under project_dir, ignore-filtered."""
    current = [project_dir]
    for _ in range(depth):
        nxt: list[Path] = []
        for parent in current:
            try:
                entries = sorted(parent.iterdir())
            except (PermissionError, OSError):
                continue
            for p in entries:
                if not p.is_dir() or p.is_symlink():
                    continue
                if p.name in _IGNORE_DIRS:
                    continue
                if p.name.startswith(".") and p.name not in _ALLOWED_DOT_DIRS:
                    continue
                nxt.append(p)
        current = nxt
    return current


def find_project_roots(project_dir: Path) -> "tuple[list[Path], int]":
    """Return (roots_to_analyze, total_discovered).

    roots_to_analyze always starts with project_dir. Nested roots are ordered by
    manifest priority first and path lexicographically only as a tie-break, then
    capped at _MAX_PROJECT_ROOTS. Deterministic at both levels.

    total_discovered counts every root found (including project_dir), so callers
    can report truncation instead of silently looking like full coverage.
    """
    nested: list[Path] = []
    for depth in range(1, _MAX_PROJECT_ROOT_DEPTH + 1):
        for d in _candidate_root_dirs(project_dir, depth):
            if _has_manifest(d):
                nested.append(d)

    # Dedupe (a depth-2 dir can never equal a depth-1 dir, but be explicit)
    seen: set[Path] = set()
    unique: list[Path] = []
    for d in nested:
        if d not in seen:
            seen.add(d)
            unique.append(d)

    unique.sort(key=lambda d: (_marker_rank(d), _rel(d, project_dir)))
    total_discovered = 1 + len(unique)
    roots = [project_dir] + unique[: max(0, _MAX_PROJECT_ROOTS - 1)]
    return roots, total_discovered


# ─── File inventory — the single source of truth for enumeration (ADR 0009) ───
#
# scan_project() answers exactly ONE question: which files exist? It inventories
# the filesystem and nothing else. NO semantic classification, architecture
# heuristic or collection policy may be added to it — it does not detect
# frameworks, does not decide what an entity is, does not apply budget, does not
# order by relevance. Those belong to the consumers.
#
# The invariant matters because scan_project becomes the most central point of
# Discovery: five consumers depend on it, which makes it exactly where every
# future detection will FEEL natural to bolt on ("I'm already walking everything,
# might as well detect React here") — and that is how a pure inventory degenerates
# into a coupled classifier nobody can test in isolation.
#
# Derived subsets are never persisted here: dividing by PLATFORM DEFINITION
# belongs to the inventory (source_paths), dividing by ARCHITECTURAL MEANING
# belongs to whoever interprets it (no frontend_paths / entity_paths).


@dataclass(frozen=True)
class _FileInventory:
    """Filesystem inventory. Population, not interpretation.

    CONTRACT — these two fields, and nothing beyond them:
      - relative posix-normalized paths
      - deterministic order, independent of OS listing order
      - no duplicates; no file under two paths (symlinks neither followed nor listed)
      - no architectural classification
      - temporal stability: only path and existence matter, never metadata
        (mtime/permissions/size) — otherwise the same commit would yield different
        maps on two machines.
    """

    all_paths: tuple[str, ...]
    source_paths: tuple[str, ...]


def scan_project(project_dir: Path) -> _FileInventory:
    """Single source of truth for structural enumeration. No reads, no budget."""
    found: set[str] = set()

    for p in project_dir.rglob("*"):
        # Symlinks out: rglob does not recurse into symlinked dirs, but is_file()
        # is True for a symlink to a file — without this the same content would be
        # enumerated twice under two paths, inflating the population and possibly
        # producing two nodes for the same code.
        if p.is_symlink() or not p.is_file():
            continue
        rel = _rel(p, project_dir)
        if not _in_ignored(rel):
            found.add(rel)

    # Sort the RELATIVE POSIX STRINGS, never the Path objects: Path comparison uses
    # the OS flavour, which on Windows is case-insensitive. Sorting Paths would make
    # the order differ between Windows and Linux for the same tree — and because the
    # content budget cuts collection mid-way, order decides WHICH files get read.
    all_paths = sorted(found)
    source_paths = [
        rel for rel in all_paths
        if PurePosixPath(rel).suffix.lower() in _SOURCE_EXTENSIONS
    ]
    return _FileInventory(
        all_paths=tuple(all_paths), source_paths=tuple(source_paths)
    )


# ─── Collector ────────────────────────────────────────────────────────────────

class _Collector:
    """Stateful accumulator for file collection. Public properties expose read-only views."""

    def __init__(self) -> None:
        self.collected: list[tuple[str, str]] = []
        self._seen: set[str] = set()
        self._chars = 0
        self._truncated: set[str] = set()
        self._soft_limit: int | None = None
        self._roots_discovered = 0
        self._roots_analyzed = 0

    # ── Soft limit: makes a phase budget an invariant instead of a convention ──

    @property
    def _cap(self) -> int:
        if self._soft_limit is None:
            return _MAX_TOTAL_CHARS
        return min(self._soft_limit, _MAX_TOTAL_CHARS)

    def set_soft_limit(self, limit: int) -> None:
        self._soft_limit = limit

    def clear_soft_limit(self) -> None:
        self._soft_limit = None

    def record_project_roots(self, *, discovered: int, analyzed: int) -> None:
        self._roots_discovered = discovered
        self._roots_analyzed = analyzed

    def add(self, rel: str, content: str) -> bool:
        if rel in self._seen or self._chars >= self._cap:
            return False
        self._seen.add(rel)
        self.collected.append((rel, content))
        self._chars += len(content)
        if _TRUNCATION_MARKER in content[-60:]:
            self._truncated.add(rel)
        return True

    def has(self, rel: str) -> bool:
        return rel in self._seen

    def at_limit(self) -> bool:
        return self._chars >= self._cap

    # ── Public read-only views (Fase 2 contract) ──────────────────────────────

    @property
    def total_chars(self) -> int:
        return self._chars

    @property
    def truncated_files(self) -> frozenset[str]:
        return frozenset(self._truncated)

    @property
    def dirs_seen(self) -> frozenset[str]:
        return frozenset(p.split("/")[0] for p in self._seen)

    @property
    def budget_used_pct(self) -> float:
        return round(self._chars / _MAX_TOTAL_CHARS * 100, 1)


# ─── File helpers ─────────────────────────────────────────────────────────────

def _file_cap(path: "Path | PurePosixPath") -> int:
    name = path.name.lower()
    if name in _FILE_NAME_CAPS:
        return _FILE_NAME_CAPS[name]
    s = str(path).replace("\\", "/").lower()
    for suffix, cap in _FILE_SUFFIX_CAPS:
        if s.endswith(suffix):
            return cap
    if any(marker in s for marker in _MODEL_DIR_MARKERS):
        return _MODEL_DIR_CAP
    return _MAX_FILE_CHARS


def _read_file(path: Path, limit: int = _MAX_FILE_CHARS) -> str | None:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
        if len(text) > limit:
            text = text[:limit] + f"\n... [truncated at {limit} chars]"
        return text
    except Exception:
        return None


def _rel(path: Path, base: Path) -> str:
    return str(path.relative_to(base)).replace("\\", "/")


def _in_ignored(rel_path: str) -> bool:
    parts = rel_path.replace("\\", "/").split("/")
    return any(p in _IGNORE_DIRS for p in parts)


def _is_maes_generated(rel: str, content: str) -> bool:
    dir_part = "/".join(rel.replace("\\", "/").split("/")[:-1])
    if dir_part in _MAES_ADAPTER_DIRS:
        return True
    snippet = content[:500]
    return any(m in snippet for m in _MAES_GENERATED_MARKERS)


# ─── Internal doc collector ───────────────────────────────────────────────────

class _DocCollector:
    def __init__(self) -> None:
        self.docs: list[tuple[str, str]] = []
        self._seen: set[str] = set()
        self._chars = 0

    def try_add(self, rel: str, p: Path) -> None:
        if rel in self._seen or self._chars >= _MAX_MIGRATE_CHARS or len(self.docs) >= _MAX_MIGRATE_FILES:
            return
        content = _read_file(p, limit=_MAX_DOC_FILE_CHARS)
        if not content or _is_maes_generated(rel, content):
            return
        self._seen.add(rel)
        self.docs.append((rel, content))
        self._chars += len(content)


# ─── Collection sub-routines ──────────────────────────────────────────────────

def collect_existing_docs(project_dir: Path) -> list[tuple[str, str]]:
    """Collect AI adapter files and project docs. Skips MAES-generated files."""
    col = _DocCollector()
    for name in _AI_ADAPTER_FILES + _DOC_ROOT_FILES:
        p = project_dir / name
        if p.exists() and p.is_file():
            col.try_add(name, p)
    for pattern in _AI_ADAPTER_GLOBS + _DOC_GLOBS:
        for p in sorted(project_dir.glob(pattern)):
            if p.is_file():
                col.try_add(_rel(p, project_dir), p)
    return col.docs


def _collect_ci_workflows(col: _Collector, project_dir: Path) -> None:
    candidates: list[Path] = []
    for pattern in _CI_GLOBS:
        candidates.extend(project_dir.glob(pattern))
    for p in sorted(candidates)[:_MAX_CI_FILES]:
        if col.at_limit():
            break
        content = _read_file(p, limit=8_000)
        if content:
            col.add(_rel(p, project_dir), content)


def _matches_glob(rel: str, pattern: str) -> bool:
    """Match a `**/tail` or exact-path pattern against a project-relative path.

    fnmatch's `*` crosses `/`, so `*/tail` reproduces `**/tail` semantics exactly —
    no custom glob translator needed.
    """
    if pattern.startswith("**/"):
        tail = pattern[3:]
        return fnmatchcase(rel, tail) or fnmatchcase(rel, "*/" + tail)
    return fnmatchcase(rel, pattern)


def _collect_auth_models(
    col: _Collector, project_dir: Path, *, inventory: _FileInventory | None = None
) -> None:
    """Collect likely auth/tenant model files.

    Filters the inventory instead of running 36 recursive globs. That also fixes a
    correctness bug: unlike _collect_domain_models, this never called _in_ignored,
    so `.venv/**/models/user.py` or `node_modules/**/model.ts` could be collected
    as project domain models. The inventory is already ignore-filtered.
    """
    paths = inventory.all_paths if inventory else None
    for pattern in _AUTH_FALLBACK_GLOBS:
        if paths is None:
            matches = [_rel(p, project_dir) for p in sorted(project_dir.glob(pattern))]
        else:
            matches = [rel for rel in paths if _matches_glob(rel, pattern)]
        for rel in matches[:2]:
            p = project_dir / rel
            if p.is_file():
                content = _read_file(p, limit=10_000)
                if content:
                    col.add(rel, content)


# Signal 1: multi-component filename suffixes — TypeScript, JavaScript, Python.
# These languages have an established convention of encoding the file role in
# the suffix (e.g. user.entity.ts, user.model.py). Path-agnostic.
_ENTITY_MULTI_SUFFIXES = frozenset({
    ".entity.ts", ".model.ts", ".schema.ts",   # TypeScript (TypeORM, NestJS, Mongoose)
    ".entity.js", ".model.js",                  # JavaScript
    ".model.py", ".entity.py", ".schema.py",    # Python (Django, SQLModel, Pydantic)
})

# Signal 2: stem keywords — covers all supported source languages that lack a
# multi-suffix convention (Go, Java, Kotlin, Rust, Ruby, PHP).
# Checks whether the filename stem (without extension) contains a model keyword.
# Example matches: UserModel.java, user_entity.go, schema.rs, domain_types.kt
_ENTITY_STEM_KEYWORDS = frozenset({"model", "entity", "schema", "domain"})

_MAX_ENTITY_FILES = 40


def _is_entity_file(p: "Path | PurePosixPath") -> bool:
    """True if the file is likely an entity/model definition — path-agnostic.

    Only reads name/suffix/stem, so a PurePosixPath over a relative path works.
    """
    name_lower = p.name.lower()
    if any(name_lower.endswith(suf) for suf in _ENTITY_MULTI_SUFFIXES):
        return True
    # For other source languages: keyword in stem + known source extension
    if p.suffix.lower() in _SOURCE_EXTENSIONS:
        return any(kw in p.stem.lower() for kw in _ENTITY_STEM_KEYWORDS)
    return False


def _collect_domain_models(
    col: _Collector, project_dir: Path, *, inventory: _FileInventory | None = None
) -> None:
    """Collect entity/model files before BFS using two path-agnostic signals.

    Signal 1 (multi-suffix): covers TypeScript, JavaScript, Python.
    Signal 2 (stem keyword): covers Go, Java, Kotlin, Rust, Ruby, PHP.
    Languages where neither signal fires are collected via BFS; files in
    /models/, /entities/, /domain/models/ paths get a higher char cap
    (_MODEL_DIR_CAP = 12 000) in _file_cap() when BFS reaches them.

    Consumes the inventory — _is_entity_file/_file_cap only need name/suffix/stem,
    so PurePosixPath over the relative path is enough; no extra filesystem walk.
    """
    source_paths = (
        inventory.source_paths
        if inventory
        else tuple(
            _rel(p, project_dir)
            for p in sorted(project_dir.rglob("*"))
            if p.is_file() and not _in_ignored(_rel(p, project_dir))
        )
    )
    collected = 0
    for rel in source_paths:
        if col.at_limit() or collected >= _MAX_ENTITY_FILES:
            return
        if col.has(rel):
            continue
        virtual = PurePosixPath(rel)
        if _is_entity_file(virtual):
            content = _read_file(project_dir / rel, limit=_file_cap(virtual))
            if content and col.add(rel, content):
                collected += 1


def _collect_priority(
    col: _Collector,
    project_dir: Path,
    *,
    skip_existing_docs: bool = False,
    inventory: "_FileInventory | None" = None,
) -> None:
    """Priority phase — hard-capped at _PRIORITY_BUDGET_RATIO of the total budget.

    The cap is a real invariant, not a comment: col.set_soft_limit() makes add()
    and at_limit() honour it, so every sub-collector stops on its own. Previously
    auth/domain model collection was exempt and could consume up to ~480k chars
    (40 files x 12k), starving the source BFS entirely.

    Phase order is deliberate — named files, CI, auth, domain, docs — so docs, which
    contribute nothing to topology, are the first thing squeezed out.
    """
    priority_limit = int(_MAX_TOTAL_CHARS * _PRIORITY_BUDGET_RATIO)
    col.set_soft_limit(priority_limit)
    try:
        roots, discovered = find_project_roots(project_dir)
        col.record_project_roots(discovered=discovered, analyzed=len(roots))

        for root in roots:
            if col.at_limit():
                break
            for name in _PRIORITY_FILES:
                if col.at_limit():
                    break
                p = root / name
                if p.exists() and p.is_file():
                    content = _read_file(p, limit=_file_cap(p))
                    if content:
                        # Key is project-relative: identical to `name` for the root
                        # itself, and disambiguates apps/web/package.json elsewhere.
                        col.add(_rel(p, project_dir), content)

        _collect_ci_workflows(col, project_dir)
        _collect_auth_models(col, project_dir, inventory=inventory)
        _collect_domain_models(col, project_dir, inventory=inventory)
        if not skip_existing_docs:
            for rel, content in collect_existing_docs(project_dir):
                if col.at_limit():
                    break
                col.add(rel, content)
    finally:
        col.clear_soft_limit()


def _collect_migrations(col: _Collector, project_dir: Path) -> None:
    candidates: list[Path] = []
    for glob in _MIGRATION_GLOBS:
        candidates.extend(project_dir.glob(glob))
    for p in sorted(candidates, reverse=True)[:_MAX_MIGRATIONS]:
        if col.at_limit():
            break
        content = _read_file(p, limit=_file_cap(p))
        if content:
            col.add(_rel(p, project_dir), content)


def _try_add_source(col: _Collector, p: Path, project_dir: Path) -> bool:
    if not p.is_file():
        return False
    rel = _rel(p, project_dir)
    if _in_ignored(rel) or col.has(rel):
        return False
    content = _read_file(p, limit=_file_cap(p))
    return bool(content) and col.add(rel, content)


def _build_source_dir_map(
    project_dir: Path, col: _Collector, inventory: "_FileInventory | None" = None
) -> "dict[str, list[str]]":
    """Group not-yet-collected source files by parent directory.

    Consumes the inventory instead of walking the filesystem again. Keys and values
    are project-relative posix strings, so ordering is OS-independent.
    """
    from collections import defaultdict
    source_paths = (
        inventory.source_paths if inventory else scan_project(project_dir).source_paths
    )
    by_dir: dict[str, list[str]] = defaultdict(list)
    for rel in source_paths:
        if col.has(rel):
            continue
        parent = rel.rsplit("/", 1)[0] if "/" in rel else ""
        by_dir[parent].append(rel)
    return by_dir


def _drain_bfs_round_robin(
    by_dir: "dict[str, list[str]]", col: _Collector, project_dir: Path
) -> None:
    dirs = sorted(by_dir.keys())
    while dirs and not col.at_limit():
        next_dirs = []
        for d in dirs:
            if col.at_limit():
                break
            if by_dir[d]:
                _try_add_source(col, project_dir / by_dir[d].pop(0), project_dir)
                if by_dir[d]:
                    next_dirs.append(d)
        dirs = next_dirs


def _collect_sources(
    col: _Collector, project_dir: Path, inventory: "_FileInventory | None" = None
) -> None:
    by_dir = _build_source_dir_map(project_dir, col, inventory)
    _drain_bfs_round_robin(by_dir, col, project_dir)


# ─── Tree builder ─────────────────────────────────────────────────────────────

def _tree_walk(d: Path, prefix: str, depth: int, lines: list[str]) -> None:
    if depth > 4:
        return
    try:
        entries = sorted(d.iterdir(), key=lambda p: (p.is_file(), p.name))
    except PermissionError:
        return
    visible = [
        e for e in entries
        if e.name not in _IGNORE_DIRS
        and (not e.name.startswith(".") or e.name in _ALLOWED_DOT_DIRS)
    ][:30]
    for i, entry in enumerate(visible):
        connector = "└── " if i == len(visible) - 1 else "├── "
        lines.append(f"{prefix}{connector}{entry.name}{'/' if entry.is_dir() else ''}")
        if entry.is_dir():
            extension = "    " if i == len(visible) - 1 else "│   "
            _tree_walk(entry, prefix + extension, depth + 1, lines)


def build_file_tree(project_dir: Path) -> str:
    lines: list[str] = [str(project_dir.name) + "/"]
    _tree_walk(project_dir, "", 1, lines)
    return "\n".join(lines)


# ─── Public API: Stage 1 entry point ─────────────────────────────────────────

def collect_project_files(
    project_dir: Path, *, skip_existing_docs: bool = False
) -> tuple[list[tuple[str, str]], _Collector]:
    """Return ([(rel_path, content)], collector). Legacy API kept for compat."""
    col = _Collector()
    inventory = scan_project(project_dir)
    _collect_priority(
        col, project_dir, skip_existing_docs=skip_existing_docs, inventory=inventory
    )
    _collect_migrations(col, project_dir)
    _collect_sources(col, project_dir, inventory)
    return col.collected, col


def run_discovery(
    project_dir: Path, *, skip_existing_docs: bool = False
) -> DiscoveryResult:
    """Stage 1 entry point. Returns immutable DiscoveryResult.

    The filesystem is enumerated ONCE (scan_project) and the inventory is reused by
    every consumer. This is not the claim that the pipeline touches the filesystem
    a single time — build_file_tree is a different projection, and analyze_imports
    reads content — but that no two places independently enumerate the same
    population and can disagree about which files exist.
    """
    col = _Collector()
    inventory = scan_project(project_dir)
    _collect_priority(
        col, project_dir, skip_existing_docs=skip_existing_docs, inventory=inventory
    )
    _collect_migrations(col, project_dir)
    _collect_sources(col, project_dir, inventory)
    return DiscoveryResult(
        files=tuple(col.collected),
        file_tree=build_file_tree(project_dir),
        total_chars=col.total_chars,
        truncated_files=col.truncated_files,
        dirs_seen=col.dirs_seen,
        budget_used_pct=col.budget_used_pct,
        source_paths=inventory.source_paths,
        project_roots_discovered=col._roots_discovered,
        project_roots_analyzed=col._roots_analyzed,
    )
