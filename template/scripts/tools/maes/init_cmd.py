    default_scenarios = [
        ("review-backend", "maes-review",
         "Revise um diff que adiciona o endpoint POST /payments"),
        ("review-migration", "maes-review",
         "Revise um diff que adiciona a coluna deleted_at em payments_transactions"),
    ]
    for sid, agent, task in default_scenarios:
        f = scenarios_dir / f"{sid}.eval.yaml"
        if not f.exists():
            f.write_text(
                scenario_template.format(id=sid, agent=agent, task=task),
                encoding="utf-8",
            )


