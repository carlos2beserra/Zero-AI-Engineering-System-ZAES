def _patch_gitignore(project_dir: Path) -> None:
    gitignore = project_dir / ".gitignore"
    existing = gitignore.read_text(encoding="utf-8") if gitignore.exists() else ""
    to_add = [e for e in _GITIGNORE_ENTRIES if e not in existing]
    if not to_add:
        return
    block = "\n# MAES runtime artifacts\n" + "\n".join(to_add) + "\n"
    gitignore.write_text(existing.rstrip() + block, encoding="utf-8")
    print(f"  + .gitignore: added {', '.join(to_add)}")


# ─── Init-time agent deployment ─────────────────────────────────────────────

_INIT_AGENTS = ("maes-create", "maes-analyze", "maes-context-add")


def _deploy_init_agents(maes_dir: Path, project_dir: Path) -> None:
    """Deploy adapter files for the entry-point agents at init time.

    maes-create (greenfield: create from an official Blueprint), maes-analyze and
    maes-context-add (brownfield: onboard an existing codebase) are deployed to
    LLM folders (Claude, Cursor, Copilot, Continue, Windsurf) so the user can
    immediately invoke them. The remaining core agents are deployed later by
    ``maes sync`` after context has been produced.
    """
    agents_src = _TEMPLATES_DIR / "agents"
    agents_dst = maes_dir / "agents"

    # Copy only the two init agents — the rest come via _copy_templates later
    for agent_id in _INIT_AGENTS:
        src = agents_src / f"{agent_id}.agent.yaml"
        dst = agents_dst / f"{agent_id}.agent.yaml"
        if src.exists() and not dst.exists():
            shutil.copy2(src, dst)

    # Seed empty assertions so the compiler doesn't raise on a fresh project
    assertions_file = maes_dir / "context" / "inferred" / "assertions.json"
    if not assertions_file.exists():
        assertions_file.write_text("[]", encoding="utf-8")

    try:
        import yaml as _yaml
        from .compiler import build, emit
        from .adapters import generate_adapters
        from .quickstart_cmd import _copy_adapters_to_root

        config_path = maes_dir / "config.yaml"
        config_data = (
            _yaml.safe_load(config_path.read_text(encoding="utf-8"))
            if config_path.exists()
            else {}
        )
        project_name = config_data.get("project", {}).get("name", project_dir.name)
        ides = config_data.get(
            "adapters", ["claude", "cursor", "copilot", "continue", "windsurf"]
        )

        state = build(maes_dir)
        emit(maes_dir, state)

        adapter_files = generate_adapters(maes_dir, state, project_name, ides)
        # Only write files that belong to the two init agents — skip global
        # context files (e.g. maes-context.md, CLAUDE.md, copilot-instructions.md)
        # that are meaningless without project context and would just confuse users.
        for rel_path, content in adapter_files.items():
            if not any(agent_id in rel_path for agent_id in _INIT_AGENTS):
                continue
            dest = maes_dir / rel_path
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content, encoding="utf-8")

        copied = _copy_adapters_to_root(maes_dir, project_dir)
        if copied:
            visible = [p for p in copied if not p.startswith("scripts/")]
            print(f"  \u2713 {', '.join(visible[:6])}")
    except Exception as exc:
        print(f"  \u26a0 Could not generate agent files: {exc}")


# ─── Public API ───────────────────────────────────────────────────────────────

def run_init(project_dir: Path | None = None) -> None:
    if project_dir is None:
        project_dir = Path.cwd()

    maes_dir = project_dir / ".maes"

    print("\nMAES Init — Context Infrastructure Setup")
    print("─" * 50)

    if maes_dir.exists() and any(maes_dir.iterdir()):
        print(f"⚠ .maes/ already exists at {maes_dir}")
        if not _confirm("Re-initialize (will not overwrite existing context files)?", default=False):
            print("Aborted.")
            return

    print("\nProject info:")
    name = _prompt("  Project name", default=project_dir.name)
    description = _prompt("  Short description (1 sentence)")
    domain = _prompt("  Primary business domain (e.g. payments, hr, logistics)")

    print("\nCreating .maes/ structure...")
    _create_dirs(maes_dir)
    _write_config(maes_dir, name, description, domain)
    print("\nDeploying entry-point agents (maes-create, maes-analyze, maes-context-add)...")
    _deploy_init_agents(maes_dir, project_dir)
    _copy_templates(maes_dir)
    _create_eval_scenarios(maes_dir)
    _create_eval_rules(maes_dir)
    # Vendor the CI-required maes modules into .maes/vendor/maes/ so the
    # maes-validate workflow (`PYTHONPATH=.maes/vendor python -m maes`) runs in
    # CI without installing maes. Tracked in git; refreshed by `maes upgrade`.
    from .quickstart_cmd import _vendor_maes_package
    _vendor_maes_package(maes_dir)
    print("  + .maes/vendor/maes/ (CI-required modules vendored)")
    _patch_gitignore(project_dir)

    print("\n" + "─" * 50)
    print("\u2713 MAES initialized successfully!\n")

    print("Next steps — choose your path:\n")
    print("  NEW project (greenfield) — create from an official Blueprint:")
    print("       Claude (Desktop/Code) →  /maes-create            (slash command)")
    print("       GitHub Copilot        →  /maes-create            (slash command)")
    print("       Cursor                →  @maes-create            (@ mention)")
    print("       The agent shows the homologated catalogue; you pick one, confirm, and it")
    print("       scaffolds with official tools + seeds org context + runs maes sync.\n")
    print("  EXISTING project (brownfield) — onboard your codebase:")
    print("       Claude / Copilot      →  /maes-analyze           (slash command)")
    print("       Cursor                →  @maes-analyze           (@ mention)")
    print("       Continue / Windsurf   →  auto-loaded             (just describe your task)")
    print("       Then: edit .maes/context/human/*.md  →  maes sync  →  maes explain status")
    print()
