# ─── Input helpers ────────────────────────────────────────────────────────────

def _prompt(msg: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    try:
        value = input(f"{msg}{suffix}: ").strip()
    except (KeyboardInterrupt, EOFError):
        print("\nAborted.")
        sys.exit(0)
    return value or default


def _prompt_list(msg: str) -> list[str]:
    raw = _prompt(msg)
    return [x.strip() for x in raw.split(",") if x.strip()]


def _confirm(msg: str, default: bool = True) -> bool:
    hint = "Y/n" if default else "y/N"
    try:
        value = input(f"{msg} [{hint}]: ").strip().lower()
    except (KeyboardInterrupt, EOFError):
        print("\nAborted.")
        sys.exit(0)
    if not value:
        return default
    return value.startswith("y")


# ─── Validation of analysis JSON ──────────────────────────────────────────────

def _validate_analysis_json(path: Path) -> dict | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as e:
        print(f"  ✗ Could not parse JSON: {e}")
        return None

    required = ["project", "stack", "gaps"]
    missing = [k for k in required if k not in data]
    if missing:
        print(f"  ✗ Missing required fields: {missing}")
        return None

    gaps = data.get("gaps", {})
    if not gaps.get("ai_likely_mistakes"):
        print("  ⚠ 'gaps.ai_likely_mistakes' is empty — "
              "this is the most important field. Continue anyway? ")
        if not _confirm("  Continue?", default=False):
            return None

    return data


