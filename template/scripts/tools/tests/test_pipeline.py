_HUMAN_DECISIONS = """\
---
layer: 4
ttl: 180d
owner: team:architecture
confidence: explicit
---

## Decisions

- MAES is a context compiler — never add LLM calls to `compiler.py` directly.
- Never edit `.maes/synthesis/**` directly — generated by `maes sync`.
- Never edit `**/CLAUDE.md` directly — generated by `maes sync`.
- Never edit `.cursor/rules/**` directly — compiled adapters.
"""


def _build_maes(tmp_path, gaps: dict, human_md: str = _HUMAN_DECISIONS) -> Path:
    maes = tmp_path / ".maes"
    (maes / "context" / "inferred").mkdir(parents=True)
    (maes / "context" / "human").mkdir(parents=True)
    # MAES v2: convert gaps dict to canonical assertions.json
    from maes.canonicalization.assertions import build_assertions
    assertions = build_assertions({"gaps": gaps})
    (maes / "context" / "inferred" / "assertions.json").write_text(
        json.dumps([a.to_dict() for a in assertions], ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (maes / "context" / "human" / "decisions.md").write_text(human_md, encoding="utf-8")
    return maes


def _run(maes_dir):
    from maes.compiler import build
    return build(maes_dir)


