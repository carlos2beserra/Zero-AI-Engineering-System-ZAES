# ─── Stage 2: run_arch_builder integration ────────────────────────────────────


def _make_discovery(files: list[tuple[str, str]]):
    from maes.pipeline.contracts import DiscoveryResult
    return DiscoveryResult(
        files=tuple(files),
        file_tree="",
        total_chars=sum(len(c) for _, c in files),
        truncated_files=frozenset(),
        dirs_seen=frozenset({f.split("/")[0] for f, _ in files}),
        budget_used_pct=0.0,
    )


def _make_dep(boundary_map: dict | None = None):
    from maes.pipeline.contracts import DepResult
    return DepResult(violations=(), boundary_map=boundary_map or {})


def test_run_arch_builder_returns_arch_map_result(tmp_path):
    """run_arch_builder produces an ArchitectureMapResult with expected fields."""
    from maes.pipeline.stage_2_arch_builder import run_arch_builder
