def test_collapse_layer_group_absorbs_layer_children():
    """A parent whose children are all layer-only dirs collapses them all."""
    from maes.arch_analysis import build_candidates, collapse_candidates
    files = [
        ("src/auth/auth.module.py", ""),              # makes src/auth a candidate
        ("src/auth/controllers/a.controller.py", ""),  # 3 files in controllers
        ("src/auth/controllers/b.controller.py", ""),
        ("src/auth/controllers/c.controller.py", ""),
        ("src/auth/services/a.service.py", ""),        # 3 files in services
        ("src/auth/services/b.service.py", ""),
        ("src/auth/services/c.service.py", ""),
    ]
    candidates = build_candidates(files)
    collapsed = collapse_candidates(candidates, layer_map={})

    paths = {c.path for c in collapsed}
    # controllers and services are layer-only dirs — must be absorbed into src/auth
    assert "src/auth/controllers" not in paths, "Layer-group child controllers must be absorbed"
    assert "src/auth/services" not in paths, "Layer-group child services must be absorbed"
    assert "src/auth" in paths, "Parent src/auth must survive"

    auth = next(c for c in collapsed if c.path == "src/auth")
    assert auth.file_count == 7  # 1 + 3 + 3


def test_collapse_coalesce_up_merges_tiny_dirs():
    """Directories with < 3 files and no semantic weight merge into their parent."""
    from maes.arch_analysis import build_candidates, collapse_candidates
    files = [
        ("src/modules/base.py", ""),               # makes src/modules a candidate
        ("src/modules/payments/helper.py", ""),    # 1 file, no entry_point → tiny
    ]
    candidates = build_candidates(files)
    collapsed = collapse_candidates(candidates, layer_map={})

    paths = {c.path for c in collapsed}
    # payments/ has 1 file and no semantic weight → must coalesce into src/modules
    assert "src/modules/payments" not in paths, "Tiny dir must be absorbed by parent"
    assert "src/modules" in paths
    parent = next(c for c in collapsed if c.path == "src/modules")
    assert "src/modules/payments" in parent.collapsed_from


def test_collapse_semantic_weight_prevents_coalesce():
    """A directory with entry_points (semantic_weight > 0) is never coalesced, even when tiny."""
    from maes.arch_analysis import build_candidates, collapse_candidates
    ep_content = "@app.post('/auth/login')\ndef login(): pass"
    files = [
        ("src/modules/base.py", ""),
        ("src/modules/auth/auth.service.py", ep_content),  # has entry_point → weight > 0
        ("src/modules/auth/auth.helper.py", ""),           # 2 files total — would normally coalesce
        ("src/modules/tiny/tiny.py", ""),                  # 1 file, no entry_point → coalesces
    ]
    candidates = build_candidates(files)
    # Pass files so semantic weights are computed
    collapsed = collapse_candidates(candidates, layer_map={}, files=files)

    paths = {c.path for c in collapsed}
    assert "src/modules/auth" in paths, "Auth with entry_point must survive despite file_count < 3"
    assert "src/modules/tiny" not in paths, "Tiny dir without semantic weight must be absorbed"


