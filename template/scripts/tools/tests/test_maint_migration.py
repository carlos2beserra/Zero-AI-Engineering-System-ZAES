"""Tests for the maintainer dev-tool `python -m maint migration create`.

These exercise maint/ (internal tooling, not the public CLI). Generation is
redirected to a tmp dir via monkeypatch so the real maes/migrations/ is never
touched.
"""

from __future__ import annotations

import importlib.util

import pytest

from maes.migrations import Migration
from maint import paths
from maint.__main__ import main


@pytest.fixture
def tmp_migrations(tmp_path, monkeypatch):
    monkeypatch.setattr(paths, "migrations_dir", lambda: tmp_path)
    return tmp_path


def _load(path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_create_generates_valid_discoverable_migration(tmp_migrations):
    rc = main(["migration", "create", "--from", "1.5.0", "--to", "1.6.0",
               "--description", "demo migration"])
    assert rc == 0

    generated = tmp_migrations / "m_1_5_0_to_1_6_0.py"
    assert generated.exists()

    module = _load(generated)
    # conforms to the contract shape that maes.migrations auto-discovery expects
    assert isinstance(module.MIGRATION, Migration)
    assert module.MIGRATION.from_version == "1.5.0"
    assert module.MIGRATION.to_version == "1.6.0"
    assert module.MIGRATION.description == "demo migration"
    # header + auditability
    assert "Generated by MAES Development Tools" in generated.read_text(encoding="utf-8")
    # _run is a guarded stub until the maintainer implements it
    with pytest.raises(NotImplementedError):
        module.MIGRATION.run(tmp_migrations)


def test_create_rejects_invalid_version(tmp_migrations):
    rc = main(["migration", "create", "--from", "1.2", "--to", "1.3.0",
               "--description", "x"])
    assert rc == 1
    assert not any(tmp_migrations.glob("m_*.py"))


def test_create_rejects_non_forward(tmp_migrations):
    rc = main(["migration", "create", "--from", "1.3.0", "--to", "1.2.0",
               "--description", "x"])
    assert rc == 1
    assert not any(tmp_migrations.glob("m_*.py"))


def test_create_rejects_duplicate_from_version(tmp_migrations):
    # 0.0.0 is already a registered from_version in the real MIGRATIONS registry.
    rc = main(["migration", "create", "--from", "0.0.0", "--to", "9.9.9",
               "--description", "x"])
    assert rc == 1
    assert not any(tmp_migrations.glob("m_*.py"))


def test_create_refuses_overwrite(tmp_migrations):
    args = ["migration", "create", "--from", "2.0.0", "--to", "2.1.0",
            "--description", "first"]
    assert main(args) == 0
    assert main(args) == 1  # second time: file exists → refuse


def test_migration_filename_derivation():
    assert paths.migration_filename("1.1.0", "1.2.0") == "m_1_1_0_to_1_2_0.py"


def test_create_rejects_triple_quote_description(tmp_migrations):
    rc = main(["migration", "create", "--from", "3.0.0", "--to", "3.1.0",
               "--description", 'breaks """ the docstring'])
    assert rc == 1
    assert not any(tmp_migrations.glob("m_*.py"))


def test_create_description_with_double_quote_stays_valid(tmp_migrations):
    # A lone double quote is legitimate (e.g. Add "foo" support) and must produce a
    # syntactically valid, importable module.
    rc = main(["migration", "create", "--from", "3.0.0", "--to", "3.1.0",
               "--description", 'Add "foo" support'])
    assert rc == 0
    module = _load(tmp_migrations / "m_3_0_0_to_3_1_0.py")
    assert module.MIGRATION.description == 'Add "foo" support'
