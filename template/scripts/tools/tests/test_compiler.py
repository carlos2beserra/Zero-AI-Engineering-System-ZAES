# ─── Helpers ──────────────────────────────────────────────────────────────────

def _assertion(claim, type_="CONSTRAINT", layer=4, paths=None, confidence="explicit", subject=None):
    return Assertion(
        id=Assertion.make_id(claim),
        claim=claim,
        type=type_,
        layer=layer,
        subject=subject,
        paths=paths or [],
        confidence=confidence,
        source="human/decisions.md",
        ttl="180d",
        last_verified="2026-01-01",
        owner="team",
    )


