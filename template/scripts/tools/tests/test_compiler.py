def test_anti_hallucination_excludes_marker_claims():
    # derive_hot_context is the anti-hallucination projection (layers 1–3,
    # explicit/inferred-high). A marker-bearing claim must never leak in.
    clean = _assertion("Senhas nunca trafegam em plaintext", layer=1, confidence="explicit")
    marked = _assertion(
        "[INFERRED] dados cifrados em repouso — confirme ou remova após revisão",
        layer=1, confidence="explicit",
    )
    hot = derive_hot_context([clean, marked])
    claims = [h["claim"] for h in hot]
    assert clean.claim in claims
    assert all(not _has_unresolved_marker(c) for c in claims)
