# ─── PR3: emit() architecture_map pass-through ────────────────────────────────


def test_emit_writes_arch_map_when_state_has_arch_map(tmp_path):
    import json
    from maes.compiler import emit
    from maes.models import ArchitectureNode, State
    maes = tmp_path / ".maes"
    (maes / "synthesis").mkdir(parents=True)
    # emit() reads inferred/architecture_map.json and copies it to synthesis/
    inferred_dir = maes / "context" / "inferred"
    inferred_dir.mkdir(parents=True)
    inferred_payload = {
        "schema_version": "1.0",
        "nodes": [{"id": "src_auth", "stable_key": "src_auth", "name": "auth",
                   "path": "src/auth", "type": "Service", "domain": "auth",
                   "domain_confidence": 0.9, "visibility": "obvious",
                   "entry_points": [], "dependencies": [], "file_count": 0}],
        "coverage_pct": 1.0,
        "files_assigned": 1,
        "files_total": 1,
        "node_quality": {},
        "generated_at": "2026-06-01",
    }
    (inferred_dir / "architecture_map.json").write_text(
        json.dumps(inferred_payload), encoding="utf-8"
    )
    node = ArchitectureNode(
        id="src_auth", stable_key="src_auth", name="auth",
        path="src/auth", type="Service", domain="auth",
        domain_confidence=0.9, visibility="obvious",
    )
    state = State(modules=[], domains=[], assertions=[], architecture_map=[node])
    emit(maes, state)
    arch_file = maes / "synthesis" / "architecture_map.json"
    assert arch_file.exists()
    data = json.loads(arch_file.read_text(encoding="utf-8"))
    assert data["schema_version"] == "1.0"
    assert len(data["nodes"]) == 1
    assert data["nodes"][0]["id"] == "src_auth"
    assert data["nodes"][0]["stable_key"] == "src_auth"
    assert "coverage_pct" in data


